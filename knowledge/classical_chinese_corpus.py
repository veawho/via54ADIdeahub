def init_classical_chinese_table(db_path: Path = None):
    """Create and populate the classical_chinese_masterpieces table in SQLite."""
    db_file = db_path or (PROJECT_ROOT / "via54_kb.db")
    conn = sqlite3.connect(str(db_file))
    cursor = conn.cursor()

    cursor.execute("""
        CREATE TABLE IF NOT EXISTS classical_chinese_masterpieces (
            id INTEGER PRIMARY KEY,
            title TEXT NOT NULL,
            author TEXT NOT NULL,
            dynasty TEXT NOT NULL,
            genre TEXT NOT NULL,
            golden_lines TEXT NOT NULL,
            full_text TEXT NOT NULL,
            rhetorical_mechanisms TEXT NOT NULL,
            emotional_archetype TEXT NOT NULL,
            copywriting_application TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
    """)

    for item in CLASSICAL_CHINESE_DATA:
        cursor.execute("""
            INSERT OR REPLACE INTO classical_chinese_masterpieces
            (id, title, author, dynasty, genre, golden_lines, full_text,
             rhetorical_mechanisms, emotional_archetype, copywriting_application)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            item["id"],
            item["title"],
            item["author"],
            item["dynasty"],
            item["genre"],
            item["golden_lines"],
            item["full_text"],
            item["rhetorical_mechanisms"],
            item["emotional_archetype"],
            item["copywriting_application"]
        ))

    conn.commit()
    conn.close()

    json_file = PROJECT_ROOT / "knowledge" / "classical_chinese_corpus.json"
    json_file.write_text(json.dumps({
        "version": "v1.0.0",
        "description": "Canonical Classical Chinese Poetry & Prose Masterpieces Corpus",
        "total_items": len(CLASSICAL_CHINESE_DATA),
        "items": CLASSICAL_CHINESE_DATA
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"✅ Successfully initialized {len(CLASSICAL_CHINESE_DATA)} Classical Chinese Masterpieces in DB & JSON!")


if __name__ == "__main__":
    init_classical_chinese_table()

def init_classical_chinese_full_kb(db_path: Path = None):
    """Create and populate classical_chinese_fulltext and classical_chinese_golden_quotes tables."""
    db_file = db_path or (PROJECT_ROOT / "via54_kb.db")
    conn = sqlite3.connect(str(db_file))
    cursor = conn.cursor()

    # 1. classical_chinese_fulltext 表
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS classical_chinese_fulltext (
            id INTEGER PRIMARY KEY,
            genre TEXT NOT NULL,
            dynasty TEXT NOT NULL,
            author TEXT NOT NULL,
            title TEXT NOT NULL,
            subtitle_or_tune TEXT,
            full_text TEXT NOT NULL,
            background_and_annotation TEXT,
            aesthetic_features TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
    """)

    for r in FULLTEXT_RECORDS:
        cursor.execute("""
            INSERT OR REPLACE INTO classical_chinese_fulltext
            (id, genre, dynasty, author, title, subtitle_or_tune, full_text, background_and_annotation, aesthetic_features)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            r["id"], r["genre"], r["dynasty"], r["author"], r["title"],
            r["subtitle_or_tune"], r["full_text"], r["background_and_annotation"], r["aesthetic_features"]
        ))

    # 2. classical_chinese_golden_quotes 表
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS classical_chinese_golden_quotes (
            id INTEGER PRIMARY KEY,
            fulltext_id INTEGER,
            quote_text TEXT NOT NULL,
            work_title TEXT NOT NULL,
            author TEXT NOT NULL,
            dynasty TEXT NOT NULL,
            genre TEXT NOT NULL,
            rhetorical_mechanisms TEXT NOT NULL,
            emotional_archetype TEXT NOT NULL,
            copywriting_application TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        );
    """)

    for q in GOLDEN_QUOTES_DATA:
        cursor.execute("""
            INSERT OR REPLACE INTO classical_chinese_golden_quotes
            (id, fulltext_id, quote_text, work_title, author, dynasty, genre,
             rhetorical_mechanisms, emotional_archetype, copywriting_application)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            q["id"], q["fulltext_id"], q["quote_text"], q["work_title"], q["author"],
            q["dynasty"], q["genre"], q["rhetorical_mechanisms"], q["emotional_archetype"], q["copywriting_application"]
        ))

    conn.commit()
    conn.close()

    # Export JSONs
    ft_json = PROJECT_ROOT / "knowledge" / "classical_chinese_fulltext.json"
    ft_json.write_text(json.dumps({
        "version": "v2.0.0",
        "description": "Full Text Repository of Classical Chinese Masterpieces (诗经、楚辞、赋、唐诗、宋词、元曲、散文)",
        "total_works": len(FULLTEXT_RECORDS),
        "works": FULLTEXT_RECORDS
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    gq_json = PROJECT_ROOT / "knowledge" / "classical_chinese_golden_quotes.json"
    gq_json.write_text(json.dumps({
        "version": "v2.0.0",
        "description": "Extracted Golden Quotes from Classical Chinese Masterpieces with Rhetoric & Copywriting Directives",
        "total_quotes": len(GOLDEN_QUOTES_DATA),
        "quotes": GOLDEN_QUOTES_DATA
    }, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"✅ Successfully initialized {len(FULLTEXT_RECORDS)} Classical Chinese Fulltexts and {len(GOLDEN_QUOTES_DATA)} Golden Quotes in DB & JSON!")


if __name__ == "__main__":
    init_classical_chinese_full_kb()
